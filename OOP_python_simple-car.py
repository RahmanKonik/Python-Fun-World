#First python program: create a simple car and test it.

class Car:
    def __init__(self, brand, color):
        self.brand = brand
        self.color = color

    def car_show_info(self):
        print("Brand: ", self.brand)
        print("Color: ", self.color)

car1 = Car("Toyota", "Grey")
car2 = Car("Tesla", "Blue")

car1.car_show_info()
car2.car_show_info()


